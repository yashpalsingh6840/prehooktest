    /// <summary>The one shape this pilot can build 2 real, distinct, ordinal-sortable file names
    /// for -- a single "*" wildcard, either bare or followed by a literal extension. Anything more
    /// complex (multiple wildcards, "?" placeholders, a literal prefix before the "*") is out of
    /// pilot scope: no test, no gap (genuinely unsupported, not a guess at what such a pattern
    /// would mean).</summary>
    internal static bool TryBuildTestFileNames(string fileSpec, out string name1, out string name2)
    {
        name1 = "";
        name2 = "";
        if (fileSpec == "*")
        {
            name1 = "a.dat";
            name2 = "b.dat";
            return true;
        }
        if (fileSpec.StartsWith("*.", StringComparison.Ordinal)
            && fileSpec.IndexOf('*', 1) < 0 && fileSpec.IndexOf('?') < 0)
        {
            var ext = fileSpec[1..]; // ".ext"
            name1 = "a" + ext;
            name2 = "b" + ext;
            return true;
        }
        return false;
    }

