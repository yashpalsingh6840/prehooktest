    /// <summary>"File System Task" taxonomy row. Deliberately scoped to the one real evidenced
    /// shape -- <c>Copy</c>, with BOTH source and destination resolved from a FILE connection
    /// manager (<see cref="FileSystemActionPlan"/>'s own doc comment names the
    /// object-model-confirmed-but-never-evidenced literal-path form, and every operation other
    /// than Copy, as unevidenced) -- writing a real source file via
    /// <c>harness.FileSystemTaskPath</c> and reading the destination back afterward, the same
    /// "write to a real, isolated temp path and read the actual bytes back rather than
    /// re-implementing the runtime's own logic a second time" discipline
    /// <see cref="EmitFlatFileSinkTest"/> already uses for <c>FlatFileBulkSink</c> -- here for
    /// <c>FileSystemActionRunner</c>'s own <c>File.Copy</c> call. No test (and no gap -- this is
    /// genuinely out of pilot scope, not a newly-discovered problem) for Move/Delete/Rename/
    /// CreateDirectory, the literal-path form, or the degenerate case where the source and
    /// destination happen to resolve to the same connection manager.</summary>
    /// <summary>The one shape both <see cref="EmitFileSystemTaskTest"/> and
    /// <see cref="EmitSequenceContainerTest"/> can build a real, deterministic assertion for --
    /// see <see cref="EmitFileSystemTaskTest"/>'s own doc comment for exactly why. Kept as one
    /// shared check so the two emitters' own scope boundaries can never drift apart.</summary>
    internal static bool TryGetTestableFileSystemKeys(FileSystemActionPlan action, out string sourceKey, out string destKey)
    {
        sourceKey = "";
        destKey = "";
        if (action.Operation != "Copy") return false;
        if (action.SourceConnectionName is not { } s || action.DestinationConnectionName is not { } d) return false;
        if (s == d) return false;
        sourceKey = s;
        destKey = d;
        return true;
    }

    public static GeneratedFile? EmitFileSystemTaskTest(
        string testNamespace, string rootNamespace, string taskName, FileSystemActionPlan action)
    {
        if (!TryGetTestableFileSystemKeys(action, out var sourceKey, out var destKey)) return null;

        // taskName is the raw SSIS task display name (free text) -- must match the SANITIZED
        // method name PackageClassEmitter actually emits on the package class, since this test
        // calls that method directly (package.{safeTaskName}(...) below). See
        // PackageGenerator.SanitizeIdentifier's own doc comment.
        var safeTaskName = PackageGenerator.SanitizeIdentifier(taskName);
        var contentLiteral = ProgramEmitter.CSharpStringLiteral("ssisx starter-test file-system-task content");
        var sourceKeyLiteral = ProgramEmitter.CSharpStringLiteral(sourceKey);
        var destKeyLiteral = ProgramEmitter.CSharpStringLiteral(destKey);

        var lines = new List<string>
        {
            "// <auto-generated>",
            $"// Generated by `ssisx generate` -- a STARTER unit test for {taskName}, proving it copies a",
            "// real source file to its destination with no database involved. Regenerating this file",
            "// freely discards any hand edits -- move those into a second file instead.",
            "// </auto-generated>",
            "#nullable enable",
            $"using {rootNamespace}.TestDoubles;",
            "using Xunit;",
            "",
            $"namespace {testNamespace};",
            "",
            $"public class {safeTaskName}StepTests",
            "{",
            "    [Fact]",
            $"    public async Task {safeTaskName}_CopiesTheSourceFileToTheDestination()",
            "    {",
            "        using var harness = new PackageHarness();",
            $"        await File.WriteAllTextAsync(harness.FileSystemTaskPath({sourceKeyLiteral}), {contentLiteral});",
            "        var package = harness.Package();",
            "        var uow = harness.NewUnitOfWork();",
            "",
            $"        await package.{safeTaskName}(uow, CancellationToken.None);",
            "",
            $"        var destinationPath = harness.FileSystemTaskPath({destKeyLiteral});",
            "        Assert.True(File.Exists(destinationPath));",
            $"        Assert.Equal({contentLiteral}, await File.ReadAllTextAsync(destinationPath));",
            "    }",
            "}",
        };

        return new GeneratedFile($"{safeTaskName}StepTests.cs", Rendering.JoinLines(lines));
    }

