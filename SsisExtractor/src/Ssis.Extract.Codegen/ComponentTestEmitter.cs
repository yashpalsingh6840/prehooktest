/// <summary>
/// Per-component starter tests beyond what <see cref="SqlStatementTestEmitter"/> (Execute SQL) and
/// <see cref="TransformTestEmitter"/> (a flow's own Map()) already cover -- phase 2 of the
/// generated-tests plan (<c>Docs/Generated-Tests-Plan.md</c>).
///
/// Starts with exactly one taxonomy row: "Sink -- SQL". It reuses
/// <see cref="PipelineResolver.ResolveDestinationInput"/> for the EXACT same column set
/// <c>EntityEmitter</c> itself builds `{Entity}.cs`'s own properties from, and
/// <see cref="TransformTestEmitter.RepresentativeLiteral"/> for the exact same representative
/// values every other starter test in this tool already uses -- so a synthesized row here can
/// never disagree with what the generated entity/sink actually declare.
/// </summary>
public static class ComponentTestEmitter
{
    public static EmitResult EmitSqlSinkTest(
        string testNamespace,
        string rootNamespace,
        string entityNamespace,
        string entityName,
        string sinkMethodName,
        PipelineComponentSpec destinationComponent)
    {
        var resolved = PipelineResolver.ResolveDestinationInput(destinationComponent);
        // Independently reproduces EntityEmitter's own identifier mapping (same
        // PipelineResolver.ResolveDestinationInput list, same order) -- see
        // PackageGenerator.MakeColumnIdentifierResolver's own doc comment.
        var identifierOf = PackageGenerator.MakeColumnIdentifierResolver();
        var propertyInits = new List<string>();
        foreach (var column in resolved.Columns)
        {
            // A column with no resolvable CLR type is already reported elsewhere (EntityEmitter's
            // own gap for it) -- this starter test just leaves it unset rather than repeating that
            // gap a second time.
            if (column.Type is not { } clrType) continue;
            propertyInits.Add($"{identifierOf(column.ExternalColumnName)} = {TransformTestEmitter.RepresentativeLiteral(clrType.ClrTypeName)}");
        }

        // Nothing this pilot can synthesize a value for -- no starter test, and no gap either
        // (every column that could not resolve already has its own gap from EntityEmitter/
        // TransformEmitter; this is genuinely out of scope, not something new to report).
        if (propertyInits.Count == 0) return new EmitResult([], []);

        var initializer = string.Join(", ", propertyInits);

        var lines = new List<string>
        {
            "// <auto-generated>",
            $"// Generated by `ssisx generate` -- a STARTER unit test for {sinkMethodName}(), proving it",
            "// writes every synthesized row through IUnitOfWork with no real database involved.",
            "// Regenerating this file freely discards any hand edits -- move those into a second file",
            "// instead.",
            "// </auto-generated>",
            "#nullable enable",
            $"using {entityNamespace};",
            $"using {rootNamespace}.TestDoubles;",
            "using Xunit;",
            "",
            $"namespace {testNamespace};",
            "",
            $"public class {entityName}SinkTests",
            "{",
            "    [Fact]",
            "    public async Task WriteAsync_WritesEveryRow_ThroughTheUnitOfWork()",
            "    {",
            "        using var harness = new PackageHarness();",
            "        var uow = harness.NewUnitOfWork();",
            "        var package = harness.Package();",
            $"        var sink = package.{sinkMethodName}();",
            "",
            "        var rows = new[]",
            "        {",
            $"            new {entityName} {{ {initializer} }},",
            $"            new {entityName} {{ {initializer} }},",
            "        };",
            "",
            "        var written = await sink.WriteAsync(uow, ToAsyncEnumerable(rows), CancellationToken.None);",
            "",
            "        Assert.Equal(2, written);",
            "        var call = Assert.Single(uow.BulkInserts);",
            "        Assert.Equal(2, call.RowsWritten);",
            $"        Assert.Equal({propertyInits.Count}, call.ColumnMappings.Count);",
            "        Assert.False(string.IsNullOrWhiteSpace(call.DestinationTable));",
            "    }",
            "",
            $"    private static async IAsyncEnumerable<{entityName}> ToAsyncEnumerable(IEnumerable<{entityName}> items)",
            "    {",
            "        foreach (var item in items) yield return item;",
            "        await Task.CompletedTask;",
            "    }",
            "}",
        };

        return new EmitResult([new GeneratedFile($"{entityName}SinkTests.cs", Rendering.JoinLines(lines))], []);
    }

    /// <summary>"Sink -- flat file" taxonomy row. Unlike <see cref="EmitSqlSinkTest"/>,
    /// <c>FlatFileBulkSink&lt;TEntity&gt;</c> never touches <c>IUnitOfWork</c> at all (see that
    /// type's own doc comment) -- there is nothing to fake, so this writes to a real, isolated
    /// per-instance temp file (<c>harness.SinkFilePath</c>/the same <c>FileSourceOptions</c> key
    /// <c>PackageHarness</c> wires up for it) and reads the ACTUAL bytes back, rather than
    /// re-implementing <c>FlatFileBulkSink</c>'s own delimiter/fixed-width/header formatting logic
    /// a second time here (which would only ever prove the two copies agree with each other, not
    /// that either is right). Asserts row/line count and non-emptiness -- exact byte content is
    /// what the dtexec-comparison fixtures already prove.</summary>
    public static EmitResult EmitFlatFileSinkTest(
        string testNamespace,
        string rootNamespace,
        string entityNamespace,
        string entityName,
        string sinkMethodName,
        string fileSourceKey,
        bool hasHeader,
        string rowTerminator,
        PipelineComponentSpec destinationComponent)
    {
        var resolved = PipelineResolver.ResolveDestinationInput(destinationComponent);
        // Independently reproduces EntityEmitter's own identifier mapping -- see
        // PackageGenerator.MakeColumnIdentifierResolver's own doc comment.
        var identifierOf = PackageGenerator.MakeColumnIdentifierResolver();
        var propertyInits = new List<string>();
        foreach (var column in resolved.Columns)
        {
            if (column.Type is not { } clrType) continue;
            propertyInits.Add($"{identifierOf(column.ExternalColumnName)} = {TransformTestEmitter.RepresentativeLiteral(clrType.ClrTypeName)}");
        }

        if (propertyInits.Count == 0) return new EmitResult([], []);

        var initializer = string.Join(", ", propertyInits);
        var expectedLines = hasHeader ? 3 : 2; // header (if any) + 2 synthesized rows

        var lines = new List<string>
        {
            "// <auto-generated>",
            $"// Generated by `ssisx generate` -- a STARTER unit test for {sinkMethodName}(), proving it",
            "// writes every synthesized row to a real file (FlatFileBulkSink never touches",
            "// IUnitOfWork -- see its own doc comment) and reading the actual written bytes back, with",
            "// no real database involved. Regenerating this file freely discards any hand edits -- move",
            "// those into a second file instead.",
            "// </auto-generated>",
            "#nullable enable",
            $"using {entityNamespace};",
            $"using {rootNamespace}.TestDoubles;",
            "using Xunit;",
            "",
            $"namespace {testNamespace};",
            "",
            $"public class {entityName}SinkTests",
            "{",
            "    [Fact]",
            "    public async Task WriteAsync_WritesEveryRow_ToARealFile()",
            "    {",
            "        using var harness = new PackageHarness();",
            "        var uow = harness.NewUnitOfWork();",
            "        var package = harness.Package();",
            $"        var sink = package.{sinkMethodName}();",
            "",
            "        var rows = new[]",
            "        {",
            $"            new {entityName} {{ {initializer} }},",
            $"            new {entityName} {{ {initializer} }},",
            "        };",
            "",
            "        var written = await sink.WriteAsync(uow, ToAsyncEnumerable(rows), CancellationToken.None);",
            "",
            "        Assert.Equal(2, written);",
            $"        var filePath = harness.SinkFilePath({ProgramEmitter.CSharpStringLiteral(fileSourceKey)});",
            "        Assert.True(File.Exists(filePath));",
            "        var text = await File.ReadAllTextAsync(filePath);",
            "        Assert.False(string.IsNullOrWhiteSpace(text));",
        };

        // The row/line terminator is whatever the destination's own last physical column's
        // delimiter decodes to (FlatFileBulkSink/ResolveFlatFileSink both build header and data
        // rows the same way -- see that method's own doc comment) -- splitting on it directly
        // rather than assuming "\r\n" universally, and skipping the count assertion entirely on
        // the one case (an empty terminator) where a line count is not a meaningful concept.
        if (!string.IsNullOrEmpty(rowTerminator))
            lines.Add($"        Assert.Equal({expectedLines}, text.Split({ProgramEmitter.CSharpStringLiteral(rowTerminator)}, StringSplitOptions.RemoveEmptyEntries).Length);");

        lines.Add("    }");
        lines.AddRange(new List<string>
        {
            "",
            $"    private static async IAsyncEnumerable<{entityName}> ToAsyncEnumerable(IEnumerable<{entityName}> items)",
            "    {",
            "        foreach (var item in items) yield return item;",
            "        await Task.CompletedTask;",
            "    }",
            "}",
        });

        return new EmitResult([new GeneratedFile($"{entityName}SinkTests.cs", Rendering.JoinLines(lines))], []);
    }

    /// <summary>"Source -- CSV/fixed-width" (and, since Phase 5 of the unsupported-component-types
