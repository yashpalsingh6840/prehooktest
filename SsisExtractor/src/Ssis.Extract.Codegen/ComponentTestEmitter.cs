    private readonly record struct RawAssignment(string RawLiteral, string ExpectedLiteral);

    /// <summary>One raw (side, rawColumnName) pair's own representative value -- a plain
    /// passthrough uses <see cref="TransformTestEmitter.RepresentativeLiteral"/> directly (the raw
    /// literal IS the expected value, unconverted); a Data-Conversion-derived one reuses
    /// <see cref="TransformTestEmitter.RepresentativeDataConversion"/> so a Merge Join mapper
    /// test's own predicted value can never quietly drift from what <c>SsisFnEmitter</c>'s emitted
    /// <c>SsisFn.ToNullable*</c> body actually computes for the SAME raw string. Null means this
    /// pilot has nothing safe to assert (an unsupported Data Conversion target, or DT_WSTR with no
    /// declared width -- see that method's own doc comment).</summary>
    private static RawAssignment? ResolveRawAssignment(string rawColumnClrType, string? conversionTargetType, int? conversionLength)
    {
        if (conversionTargetType is not null)
        {
            var rep = TransformTestEmitter.RepresentativeDataConversion(conversionTargetType, conversionLength);
            return rep is { } r ? new RawAssignment(r.RawLiteral, r.ExpectedLiteral) : null;
        }

        var literal = TransformTestEmitter.RepresentativeLiteral(rawColumnClrType);
        return new RawAssignment(literal, literal);
    }

    /// <summary>"Merge Join mapper" taxonomy row: <c>Docs/Generated-Tests-Plan.md</c>'s own wording
    /// is "LeftKey / RightKey / Map over synthesized rows". A pure static-function test -- no
    /// <c>IUnitOfWork</c>/<c>PackageHarness</c> needed at all, since <c>{Mapper}.LeftKey</c>/
    /// <c>RightKey</c>/<c>Map</c> touch neither.
    ///
    /// <para>Two scenarios, both real-evidenced concerns for this exact code (RBC_Demo_ETL's own
    /// <c>DFT_SortAndMergeJoin</c>): a MATCHED pair (both sides present, asserting every key and
    /// every combined-row column's predicted value) and an UNMATCHED left row (<c>right</c> is
    /// <c>null</c> -- the one evidenced join type, LeftOuter, so a right-side column must come
    /// back <c>null</c> rather than throwing the exact <c>CS8629</c>/null-forgiving-<c>!</c> class
    /// of bug this generator's own Merge Join round had to fix once already). The second scenario
    /// is only emitted when at least one column is genuinely right-side (<see cref="MergeJoinEmitter.MergeJoinTestColumn.MayBeAbsent"/>);
    /// a hypothetical join type with no absent side at all would have nothing to assert there.</para>
    ///
    /// <para>Every raw (side, column-name) pair resolves through <see cref="ResolveRawAssignment"/>
    /// -- if the SAME raw column is referenced twice with two DIFFERENT resolutions (never
    /// evidenced, but checked defensively), or any one reference cannot be resolved at all (an
    /// unsupported Data Conversion target/width), no test is emitted, and no gap either -- this
    /// pilot's scope, not a newly discovered problem.</para>
    /// </summary>
    public static GeneratedFile? EmitMergeJoinMapperTest(
        string testNamespace,
        string leftRowTypeNamespace, string leftRowTypeName,
        string rightRowTypeNamespace, string rightRowTypeName,
        string mappingNamespace, string mapperClassName,
        MergeJoinEmitter.MergeJoinTestKey leftKeyTest, MergeJoinEmitter.MergeJoinTestKey rightKeyTest,
        IReadOnlyList<MergeJoinEmitter.MergeJoinTestColumn> testColumns)
    {
        var leftLiterals = new Dictionary<string, RawAssignment>(StringComparer.Ordinal);
        var rightLiterals = new Dictionary<string, RawAssignment>(StringComparer.Ordinal);

        bool TryAssign(Dictionary<string, RawAssignment> literals, string rawColumnName, string rawColumnClrType, string? conversionTargetType, int? conversionLength)
        {
            var resolved = ResolveRawAssignment(rawColumnClrType, conversionTargetType, conversionLength);
            if (resolved is not { } assignment) return false;
            if (literals.TryGetValue(rawColumnName, out var existing))
                return existing.RawLiteral == assignment.RawLiteral && existing.ExpectedLiteral == assignment.ExpectedLiteral;
            literals[rawColumnName] = assignment;
            return true;
        }

        if (!TryAssign(leftLiterals, leftKeyTest.RawColumnName, leftKeyTest.RawColumnClrType, leftKeyTest.ConversionTargetType, leftKeyTest.ConversionLength)) return null;
        if (!TryAssign(rightLiterals, rightKeyTest.RawColumnName, rightKeyTest.RawColumnClrType, rightKeyTest.ConversionTargetType, rightKeyTest.ConversionLength)) return null;

        foreach (var col in testColumns)
        {
            var literals = col.MayBeAbsent ? rightLiterals : leftLiterals;
            if (!TryAssign(literals, col.RawColumnName, col.RawColumnClrType, col.ConversionTargetType, col.ConversionLength)) return null;
        }

        // leftLiterals/rightLiterals are keyed by the RAW source column name (Left/Right's own
        // row types, matching SqlRowEmitter/CsvRowEmitter's own bare-sanitized declarations);
        // combinedIdentifierOf independently reproduces MergeJoinEmitter.BuildRowTypeFile's own
        // resolver over the SAME testColumns list, in the SAME order -- see
        // PackageGenerator.MakeColumnIdentifierResolver's own doc comment.
        var leftPropertyInits = string.Join(", ", leftLiterals.Select(kv => $"{PackageGenerator.SanitizeIdentifier(kv.Key)} = {kv.Value.RawLiteral}"));
        var rightPropertyInits = string.Join(", ", rightLiterals.Select(kv => $"{PackageGenerator.SanitizeIdentifier(kv.Key)} = {kv.Value.RawLiteral}"));
        var combinedIdentifierOf = PackageGenerator.MakeColumnIdentifierResolver();
        var combinedIdentifiers = testColumns.ToDictionary(c => c, c => combinedIdentifierOf(c.Name));

        var matchedAssertions = new List<string>
        {
            $"        Assert.Equal({leftLiterals[leftKeyTest.RawColumnName].ExpectedLiteral}, {mapperClassName}.LeftKey(left));",
            $"        Assert.Equal({rightLiterals[rightKeyTest.RawColumnName].ExpectedLiteral}, {mapperClassName}.RightKey(right));",
        };
        foreach (var col in testColumns)
        {
            var literals = col.MayBeAbsent ? rightLiterals : leftLiterals;
            matchedAssertions.Add($"        Assert.Equal({literals[col.RawColumnName].ExpectedLiteral}, matched.{combinedIdentifiers[col]});");
        }

        var rightSideColumns = testColumns.Where(c => c.MayBeAbsent).ToList();

        var usingNamespaces = new List<string> { leftRowTypeNamespace, rightRowTypeNamespace, mappingNamespace }.Distinct();
        var lines = new List<string>
        {
            "// <auto-generated>",
            $"// Generated by `ssisx generate` -- a STARTER unit test for {mapperClassName}, proving its",
            "// LeftKey/RightKey selectors and its Map projection produce the expected values for both a",
            "// matched pair and an unmatched left row, with no IUnitOfWork/database involved (a pure",
            "// static-function test). Regenerating this file freely discards any hand edits -- move",
            "// those into a second file instead.",
            "// </auto-generated>",
            "#nullable enable",
        };
        lines.AddRange(usingNamespaces.Select(ns => $"using {ns};"));
        lines.Add("using Xunit;");
        lines.Add("");
        lines.Add($"namespace {testNamespace};");
        lines.Add("");
        lines.Add($"public class {mapperClassName}Tests");
        lines.Add("{");
        lines.Add("    [Fact]");
        lines.Add("    public void Map_ComputesExpectedOutput_ForAMatchedPair()");
        lines.Add("    {");
        lines.Add($"        var left = new {leftRowTypeName} {{ {leftPropertyInits} }};");
        lines.Add($"        var right = new {rightRowTypeName} {{ {rightPropertyInits} }};");
        lines.Add("");
        lines.Add($"        var matched = {mapperClassName}.Map(left, right);");
        lines.Add("");
        lines.AddRange(matchedAssertions);
        lines.Add("    }");

        if (rightSideColumns.Count > 0)
        {
            lines.Add("");
            lines.Add("    [Fact]");
            lines.Add("    public void Map_LeavesRightSideColumnsNull_ForAnUnmatchedLeftRow()");
            lines.Add("    {");
            lines.Add($"        var left = new {leftRowTypeName} {{ {leftPropertyInits} }};");
            lines.Add("");
            lines.Add($"        var unmatched = {mapperClassName}.Map(left, null);");
            lines.Add("");
            foreach (var col in testColumns)
            {
                lines.Add(col.MayBeAbsent
                    ? $"        Assert.Null(unmatched.{combinedIdentifiers[col]});"
                    : $"        Assert.Equal({leftLiterals[col.RawColumnName].ExpectedLiteral}, unmatched.{combinedIdentifiers[col]});");
            }
            lines.Add("    }");
        }

        lines.Add("}");

        return new GeneratedFile($"{mapperClassName}Tests.cs", Rendering.JoinLines(lines));
    }

