        }

        // Order is only meaningful, and only asserted, among consecutive SQL children -- a File
        // System Task child never touches uow.ExecutedSql at all (see this method's own doc
        // comment), so there is nothing to compare it against.
        for (var i = 0; i + 1 < sqlStatementRefs.Count; i++)
