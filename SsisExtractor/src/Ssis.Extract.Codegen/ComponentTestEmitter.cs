            $"using {rootNamespace}.Mapping;",
            $"using {rootNamespace}.TestDoubles;",
            "using Xunit;",
            "",
            $"namespace {testNamespace};",
            "",
            $"public class {containerMethodName}StepTests",
            "{",
            "    [Fact]",
            $"    public async Task {containerMethodName}_RunsEveryChild()",
            "    {",
            "        using var harness = new PackageHarness();",
        };
